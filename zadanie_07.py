import numpy as np

print("Zera 3x3:\n", np.zeros((3, 3)))
print("Jedynki 4x4:\n", np.ones((4, 4)))
print("Macierz identyczności 5x5:\n", np.eye(5))
print("Siódemki 3x4:\n", np.full((3, 4), 7))
print("10 wartości od 0 do 1:", np.linspace(0, 1, 10))
